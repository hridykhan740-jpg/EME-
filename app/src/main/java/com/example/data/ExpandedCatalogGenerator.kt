  fun enrichAndExpand(
    baseParts: List<CatalogPart>,
    spec: BrandOemSpec,
    fitment: String,
    isEv: Boolean,
  ): List<CatalogPart> {
    val p = spec.codePrefix
    val combined = ArrayList<CatalogPart>(baseParts.size + extraModules.size)

    // 1. Keep every original assembly and pad sub-components up to 22 micro items
    baseParts.forEach { base ->
      val enrichedSubs = padSubComponents(base.id, base.oemNumber, p, base.subComponents, targetCount = 22)
      combined += base.copy(subComponents = enrichedSubs)
    }

    // 2. Append additional modular assemblies (filtering out ICE-only items on EV)
    extraModules.forEach { tpl ->
      if (isEv && (tpl.system == CatalogSystem.EXHAUST || tpl.id == "eng_timing_chain" || tpl.id == "eng_piston_ring" || tpl.id == "eng_head_gasket")) {
        return@forEach
      }
      val coreSubs = tpl.subParts.mapIndexed { idx, (subName, codeSuffix, price) ->
        PartSubComponent(
          id = "${tpl.id}_sub_${idx + 1}",
          name = subName,
          oemNumber = "$p-$codeSuffix",
          aftermarketNumber = "${tpl.aftermarketBrand.substringBefore(' ').uppercase(Locale.US)}-${codeSuffix.takeLast(5)}",
          quantity = if (subName.contains("Pair") || subName.contains("2x")) "2 pcs" else if (subName.contains("4x")) "4 pcs" else "1 pc",
          specNote = "EPC verified sub-component for $fitment",
          priceUsd = price,
        )
      }
      val paddedSubs = padSubComponents(tpl.id, "$p-${tpl.oemTail}", p, coreSubs, targetCount = 22)
      combined += CatalogPart(
        id = tpl.id,
        system = tpl.system,
        subSystem = tpl.subSystem,
        name = tpl.name,
        oemNumber = "$p-${tpl.oemTail}",
        oemManufacturer = spec.oemBrand,
        aftermarketNumber = tpl.aftermarketNumber,
        aftermarketBrand = tpl.aftermarketBrand,
        epcCatalogRef = "${spec.epcCatalogName} • ${tpl.epcFig}",
        stockStatus = if (tpl.priceUsd > 190.0) StockStatus.OEM_ORDER else StockStatus.IN_STOCK,
        warehouseQty = if (tpl.priceUsd > 190.0) 8 else 26,
        priceUsd = tpl.priceUsd,
        dispatchSla = if (tpl.priceUsd > 190.0) "OEM Express 24–48h" else "Same-day dispatch",
        specSummary = tpl.specSummary,
        fitmentNotes = "Complete assembly & hardware breakdown verified for $fitment.",
        visualKind = tpl.visualKind,
        keywords = listOf(tpl.system.displayName, tpl.subSystem, tpl.name, tpl.oemTail, tpl.aftermarketBrand),
        subComponents = paddedSubs,
      )
    }

    return combined
  }

  private fun padSubComponents(
    assemblyId: String,
    baseOem: String,
    prefix: String,
    existing: List<PartSubComponent>,
    targetCount: Int,
  ): List<PartSubComponent> {
    if (existing.size >= targetCount) return existing
    val result = ArrayList<PartSubComponent>(targetCount)
    result.addAll(existing)
    val shortCode = baseOem.filter { it.isLetterOrDigit() }.takeLast(5).ifEmpty { "10001" }
    var idx = 0
    while (result.size < targetCount) {
      val tpl = fastenerSuffixes[idx % fastenerSuffixes.size]
      val seqNum = result.size + 1
      result += PartSubComponent(
        id = "${assemblyId}_hw_${seqNum}",
        name = tpl.first,
        oemNumber = "$prefix-$shortCode-${String.format(Locale.US, "%02d", seqNum)}",
        aftermarketNumber = "OEM-HW-${shortCode}-${seqNum}",
        quantity = if (tpl.first.contains("4x")) "4 pcs" else if (tpl.first.contains("Pair")) "2 pcs" else "1 pc",
        specNote = tpl.second,
        priceUsd = tpl.third,
        stockStatus = StockStatus.IN_STOCK,
      )
      idx++
    }
    return result
  }
